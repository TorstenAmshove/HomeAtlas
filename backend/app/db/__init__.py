"""SQLite persistence -- the only place that executes SQL (ADR-0010, supersedes ADR-0005).

One connection per call (short-lived, WAL enabled) rather than a shared module-level handle --
discovery scans run in worker threads via `asyncio.to_thread` and would otherwise share a
connection across threads.

Column naming is camelCase throughout so rows can be handed to the frontend as-is without a
translation layer; the JSON-typed columns listed in `_JSON_COLUMNS` are transparently
encoded/decoded in `_core` so callers only ever see Python dicts/lists.

Layout: one module per entity group; every name is re-exported here so callers keep writing
`db.get_system(...)`. Submodules import only from `_core` and, where unavoidable, in one direction
(`accounts` -> `systems`; never the reverse). `DB_PATH` and `_ERROR_EVENT_KEEP` are defined HERE
and read at call time by the submodules, so `monkeypatch.setattr(db, ...)` keeps working.
"""
